"""The documentation screenshots of every dashboard page (`docs/screenshots/`), taken from the seeded dashboard.

What this is
    One browser test per dashboard page of the registry (`roxy.admin.pages.registry.PAGES`, 18 pages): the page opens
    in the dark theme at 1440x900 on the seeded dashboard (`dashboard`, tests/e2e/conftest.py: the real app, traffic
    sent through the real proxy, audit rows, a recommendation and a health run), every lazy card loads, every chart
    finishes, and a full-page screenshot is written. Overview and Protection are taken in the light theme too. With
    `ROXY_SCREENSHOTS=1` the files go to `docs/screenshots/<page>.png` (and `<page>-light.png`), the copies the
    README and the guides link; otherwise to a temporary directory, so an ordinary run checks the same things and
    leaves the repository alone.

Why it exists
    Plan 16.3 asks for screenshots of every dashboard page in the admin guide, generated by Playwright, so they can be
    taken again whenever a page changes instead of going stale. The checks make a screenshot honest: a picture of a
    card still loading, a card that failed, a chart without its data or a page with a console error is refused.

How it works
    `open_admin` saves the theme as the admin's preference and loads the page settled (`AdminPage.settle()` waits for
    the shared lazy card loader of `static/js/cards.js`). The test then waits until every `[data-chart]` figure has
    drawn (`data-chart-ready` is `1`, or `empty` for a series with no points), on the Live page until the tail shows
    the recorded rows the stream replays, and takes a full-page screenshot with animations off. Test ids are
    `page_<id>_<theme>` (never the bare word `live`, which the root conftest reserves).

What to read next
    tests/e2e/conftest.py (`open_admin`, `AdminPage`), tests/pages_harness.py (`DashboardServer`, the seeded data),
    README.md (the page list that links these files), docs/ADMIN_GUIDE.md.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import pytest

from roxy.admin.pages import registry

REPO = Path(__file__).resolve().parents[2]
DOCS_SHOTS = REPO / "docs" / "screenshots"
LIGHT_PAGES = ("overview", "protection")
"""Pages also taken in the light theme (the README shows both themes with them)."""

SHOTS = [(spec.id, "dark") for spec in registry.PAGES] + [(page_id, "light") for page_id in LIGHT_PAGES]

CHARTS_DONE = """() => Array.from(document.querySelectorAll('[data-chart]')).every(
  (figure) => ["1", "empty", "error"].includes(figure.dataset.chartReady))"""
FAILED_CHARTS = """() => Array.from(document.querySelectorAll('[data-chart][data-chart-ready="error"]')).map(
  (figure) => (figure.closest('[data-card]') || figure).id || "chart")"""
FAILED_CARDS = "() => Array.from(document.querySelectorAll('[data-card-error]')).map((card) => card.id)"
LAZY_LEFT = "() => Array.from(document.querySelectorAll('.page-card--lazy')).map((card) => card.id)"
TAIL_SHOWS_ROWS = """() => document.querySelectorAll('#live-tail .tail__row:not([hidden])').length > 0
  && document.querySelector('#live-tail').dataset.state === 'live'"""
"""The Live page's tail has replayed the recorded rows over the event stream (`tests/e2e/test_page_live.py`)."""


def shot_name(page_id: str, theme: str) -> str:
    """The file name of a page's screenshot: `<page>.png` in the dark theme, `<page>-light.png` in the light one."""
    return f"{page_id}.png" if theme == "dark" else f"{page_id}-{theme}.png"


def output_dir(tmp_path: Path) -> Path:
    return DOCS_SHOTS if os.environ.get("ROXY_SCREENSHOTS") == "1" else tmp_path


@pytest.mark.parametrize(("page_id", "theme"), SHOTS, ids=[f"page_{page_id}_{theme}" for page_id, theme in SHOTS])
def test_a_documentation_screenshot_shows_the_whole_settled_page(
    open_admin: Any, tmp_path: Path, page_id: str, theme: str
) -> None:
    admin = open_admin(f"/admin/{page_id}", theme=theme, width=1440, height=900)
    page = admin.page
    assert page.locator(f'html[data-theme="{theme}"]').count() == 1
    assert page.evaluate(LAZY_LEFT) == [], "a lazy card never loaded"
    admin.wait(CHARTS_DONE, timeout=20.0)
    if page_id == "live":
        admin.wait(TAIL_SHOWS_ROWS, timeout=20.0)  # a picture of the tail before the stream delivered is empty
    assert page.evaluate(FAILED_CHARTS) == [], "a chart could not draw its series"
    assert page.evaluate(FAILED_CARDS) == [], "a card failed to render"
    admin.assert_clean()
    out = output_dir(tmp_path)
    out.mkdir(parents=True, exist_ok=True)
    path = out / shot_name(page_id, theme)
    page.evaluate("window.scrollTo(0, 0)")
    page.screenshot(path=str(path), full_page=True, animations="disabled")
    assert path.stat().st_size > 10_000
