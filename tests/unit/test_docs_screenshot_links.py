"""The dashboard screenshots the documentation links: one per registry page, linked from the README, none missing.

What this is
    Checks over `docs/screenshots/` and the files that link it: every dashboard page of the registry
    (`roxy.admin.pages.registry.PAGES`) has its dark screenshot `docs/screenshots/<page id>.png`, Overview and
    Protection also their light one (`<page id>-light.png`); `README.md` lists every page by its registry title with a
    link to its screenshot and the two light ones; and every `docs/screenshots/...` link in the README and the guides
    points at a file that exists. Other files may live in the folder (the phone flow steps of
    `tests/e2e/test_phone_flows.py`).

Why it exists
    Plan 16.3 asks for screenshots of every dashboard page, generated by Playwright so they can be taken again. A page
    added to the registry without its screenshot, a renamed file or a README row left behind would send a reader to a
    missing picture; this test names the gap and the command that fills it.

How it works
    Plain file reads and a regular expression over Markdown links (`[text](path)` and `![alt](path)`); the registry is
    imported for the page ids and titles. The screenshots themselves are taken by `tests/e2e/test_docs_screenshots.py`
    (`ROXY_SCREENSHOTS=1` writes them here).

What to read next
    `tests/e2e/test_docs_screenshots.py`, `README.md` ("The dashboard"), `src/roxy/admin/pages/registry.py`.
"""

from __future__ import annotations

import re
from pathlib import Path

from roxy.admin.pages import registry

REPO = Path(__file__).resolve().parents[2]
SHOTS = REPO / "docs" / "screenshots"
README = REPO / "README.md"
LIGHT_PAGES = ("overview", "protection")
LINKING_FILES = (README, REPO / "docs" / "ADMIN_GUIDE.md", REPO / "docs" / "USER_GUIDE.md")
LINK = re.compile(r"\]\((docs/screenshots/[^)\s]+|screenshots/[^)\s]+)\)")
TAKE_AGAIN = "ROXY_SCREENSHOTS=1 .venv/bin/python -m pytest tests/e2e/test_docs_screenshots.py"


def expected_names() -> list[str]:
    return [f"{spec.id}.png" for spec in registry.PAGES] + [f"{page_id}-light.png" for page_id in LIGHT_PAGES]


def test_every_registry_page_has_its_screenshot() -> None:
    missing = [name for name in expected_names() if not (SHOTS / name).is_file()]
    assert not missing, f"missing screenshots {missing}; take them with: {TAKE_AGAIN}"


def test_the_readme_lists_every_page_with_its_screenshot() -> None:
    text = README.read_text(encoding="utf-8")
    rows = {line.split("|")[1].strip(): line for line in text.splitlines() if line.startswith("| ")}
    problems: list[str] = []
    for spec in registry.PAGES:
        row = rows.get(spec.title)
        if row is None:
            problems.append(f"no README row for the {spec.title} page")
        elif f"(docs/screenshots/{spec.id}.png)" not in row:
            problems.append(f"the {spec.title} row does not link docs/screenshots/{spec.id}.png")
    for page_id in LIGHT_PAGES:
        if f"(docs/screenshots/{page_id}-light.png)" not in text:
            problems.append(f"the README does not link docs/screenshots/{page_id}-light.png")
    assert not problems, problems


def test_every_screenshot_link_points_at_a_file() -> None:
    broken: list[str] = []
    for path in LINKING_FILES:
        if not path.is_file():
            continue
        for target in LINK.findall(path.read_text(encoding="utf-8")):
            resolved = (path.parent / target).resolve()
            if not resolved.is_file():
                broken.append(f"{path.name}: {target}")
    assert not broken, broken
