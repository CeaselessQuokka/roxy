"""Generate docs/endpoint_policy/CATALOG.md, the human-readable table of every endpoint and its default verdict.

What this is
    A standalone tool that renders `docs/endpoint_policy/endpoint_policy_seed.json` as Markdown: a summary by host
    and by category, then one table per host listing every Roblox operation with its default verdict, risk, why,
    and links to Roblox's own documentation (the feature page and the domain page, both anchored to the operation).

Why it exists
    The seed is the data Roxy ships; the catalog is how a person (or an LLM implementing BRIEF.md) reads it. Keeping
    the catalog generated means it can never disagree with the seed.

How it works
    `python3 -I scripts/gen_endpoint_catalog.py` (from the repository root) rewrites the catalog. Rows are sorted by
    host, then path, then method. Pipe characters in text are escaped so the tables stay intact.

What to read next
    docs/endpoint_policy/BRIEF.md, scripts/endpoint_policy_inventory.py.
"""

from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = ROOT / "docs" / "endpoint_policy" / "endpoint_policy_seed.json"
OUT = ROOT / "docs" / "endpoint_policy" / "CATALOG.md"
VERDICT_LABEL = {"BLOCK": "**BLOCK**", "ALLOW_TOKEN": "TOKEN", "ALLOW_ANON": "ANON"}
METHOD_ORDER = {"GET": 0, "POST": 1, "PUT": 2, "PATCH": 3, "DELETE": 4}


def cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def main() -> int:
    seed = json.loads(SEED.read_text(encoding="utf-8"))
    rows = seed["endpoints"]
    by_host: dict[str, list[dict]] = collections.defaultdict(list)
    for row in rows:
        by_host[row["host"]].append(row)
    verdicts = collections.Counter(r["verdict"] for r in rows)
    out: list[str] = [
        "# Endpoint catalog",
        "",
        "Generated by `scripts/gen_endpoint_catalog.py` from `endpoint_policy_seed.json`. Do not edit by hand:",
        "change the seed, then run the script. How to use this table: `BRIEF.md` in this folder.",
        "",
        f"Source: Roblox `{seed['source']['file']}` at commit `{seed['source']['commit'][:12]}` of "
        f"{seed['source']['repository']} ({seed['generated_on']}). {len(rows)} operations on {len(by_host)} hosts.",
        "",
        "Verdicts: **BLOCK** = refused before Roblox, never forwarded. TOKEN = forwarded with Roxy's credential. "
        "ANON = forwarded, never with the credential. Roblox sign-in column: what Roblox's reference says the "
        "endpoint accepts (`cookie-required`, `cookie-optional`, `none`, `apikey/oauth-only`). Risk: 1 harmless, "
        "2 low, 3 meaningful, 4 critical (what happens if a stranger could call it with Roxy's account).",
        "",
        f"Totals: BLOCK {verdicts['BLOCK']}, TOKEN {verdicts['ALLOW_TOKEN']}, ANON {verdicts['ALLOW_ANON']}.",
        "",
        "## Summary by host",
        "",
        "| Host | Operations | BLOCK | TOKEN | ANON | Roblox domain page |",
        "|---|---|---|---|---|---|",
    ]
    for host in sorted(by_host):
        c = collections.Counter(r["verdict"] for r in by_host[host])
        page = "https://create.roblox.com/docs/cloud/reference/domains/" + host.split(".")[0]
        out.append(
            f"| [{host}](#{host.replace('.', '')}) | {len(by_host[host])} | {c['BLOCK']} | {c['ALLOW_TOKEN']} | "
            f"{c['ALLOW_ANON']} | [docs]({page}) |"
        )
    out += [
        "",
        "## Hosts Roxy allows that Roblox does not document",
        "",
        "| Host | Default | Category | Risk | Why |",
        "|---|---|---|---|---|",
    ]
    for host, d in sorted(seed["host_defaults"].items()):
        out.append(
            f"| {host} | {VERDICT_LABEL[d['verdict']]} | {d['category']} | {d['risk']} | {cell(d['rationale'])} |"
        )
    out += ["", "## Summary by category", "", "| Category | BLOCK | TOKEN | ANON |", "|---|---|---|---|"]
    by_cat: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for r in rows:
        by_cat[r["category"]][r["verdict"]] += 1
    for cat in sorted(by_cat):
        c = by_cat[cat]
        out.append(f"| {cat} | {c['BLOCK']} | {c['ALLOW_TOKEN']} | {c['ALLOW_ANON']} |")
    for host in sorted(by_host):
        out += [
            "",
            f"## {host}",
            "",
            "| Method | Path | Roblox sign-in | Verdict | Risk | Category | What it does and why | Docs |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in sorted(by_host[host], key=lambda r: (r["path"].lower(), METHOD_ORDER.get(r["method"], 9))):
            why = cell(r["rationale"])
            if r.get("notes"):
                why += f" *Note:* {cell(r['notes'])}"
            if r.get("deprecated"):
                why += " *(deprecated)*"
            links = []
            if r.get("feature_doc"):
                links.append(f"[feature]({r['feature_doc']})")
            links.append(f"[domain]({r['domain_doc']})")
            out.append(
                f"| {r['method']} | `{cell(r['path'])}` | {r['roblox_auth']} | {VERDICT_LABEL[r['verdict']]} | "
                f"{r['risk']} | {r['category']} | {why} | {' '.join(links)} |"
            )
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
